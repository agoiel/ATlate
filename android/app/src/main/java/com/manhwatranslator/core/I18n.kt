/** Перевод фразы интерфейса на текущий язык. */
fun tr(s: String): String = if (I18n.english) I18n.EN[s] ?: s else s

/** То же, с подстановкой значений вместо %s. */
fun trf(s: String, vararg args: Any?): String = String.format(tr(s), *args)
