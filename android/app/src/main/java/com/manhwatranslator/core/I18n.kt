/**
 * Язык интерфейса. Русский текст в коде — это ключ; при английском интерфейсе
 * подставляется перевод из словаря ниже. Нет перевода — показывается русский.
 */
object I18n {
    @Volatile var english = false

    /** Языки, при которых по умолчанию остаётся русский интерфейс. */
    private val russianLocales = setOf("ru", "uk", "be", "kk", "uz", "ky", "tg")

    fun init(ctx: Context) {
        english = when (Settings(ctx).uiLang) {
            "en" -> true
            "ru" -> false
            else -> Locale.getDefault().language !in russianLocales
        }
    }

    /** Название языка посреди фразы: по-русски — со строчной («сейчас корейский»), по-английски — как есть. */
    fun lower(s: String): String = if (english) s else s.lowercase()

